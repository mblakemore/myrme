import {
  BlendFunction,
  BloomEffect,
  BrightnessContrastEffect,
  ChromaticAberrationEffect,
  DepthOfFieldEffect,
  EffectComposer,
  EffectPass,
  GodRaysEffect,
  HueSaturationEffect,
  NoiseEffect,
  RenderPass,
  SMAAEffect,
  SMAAPreset,
  ToneMappingEffect,
  ToneMappingMode,
  VignetteEffect,
} from 'postprocessing';
import * as THREE from 'three';
import type { FrameInfo, QualityPreset, QualitySettings, RenderStats, SimView, UrlParams, ViewState } from '../core';
import { MODULES } from './modules';
import { fx } from './modules/fxShared';
import { AOCompositeEffect, AOPass, FogEffect, FxScreenEffect, GradeEffect } from './modules/postlookEffects';
import { getEnv } from './modules/skyEnv';
import { QUALITY_PRESETS, createDefaultLook, createSharedUniforms, cutPlaneToVec4, type Module, type RenderContext } from './shared';

/**
 * Rendering pipeline skeleton (§5.3). Owns the canvas, WebGLRenderer, EffectComposer, quality
 * struct, shared uniforms, the sun + its single texel-snapped shadow map, and the module list.
 *
 * Streams add scene content through modules (`render/modules/*`) and tune post-processing through
 * the typed `look` object — they do not edit this file.
 *
 * Effect chain (present according to the quality preset, parameters from `look` every frame and
 * from the A3 `LookExtras` in `modules/skyEnv`):
 *   RenderPass → [AOPass: half-res depth-only AO] → { [AO composite] + depth fog } → [DoF] →
 *   { [bloom + god rays] + tone map + colour grade [+ vignette + grain] } →
 *   [chromatic aberration] → [SMAA]
 * Braces are single merged fullscreen passes; without DoF the first two braces merge into one.
 * AO reconstructs normals from depth (no extra geometry pass; honours the cutaway discard).
 */
export class Renderer {
  readonly canvas: HTMLCanvasElement;
  readonly ctx: RenderContext;
  private readonly renderer: THREE.WebGLRenderer;
  private composer!: EffectComposer;
  private readonly modules: readonly Module[];
  private gpuName = 'unknown';

  // effects (null when disabled by the preset)
  private aoPass: AOPass | null = null;
  private aoComposite: AOCompositeEffect | null = null;
  private fog: FogEffect | null = null;
  private grade: GradeEffect | null = null;
  private fxScreen: FxScreenEffect | null = null;
  private bloom: BloomEffect | null = null;
  private dof: DepthOfFieldEffect | null = null;
  private dofPass: EffectPass | null = null;
  private warmed = false;
  private godRays: GodRaysEffect | null = null;
  private toneMap: ToneMappingEffect | null = null;
  private hueSat: HueSaturationEffect | null = null;
  private brightCon: BrightnessContrastEffect | null = null;
  private vignette: VignetteEffect | null = null;
  private noise: NoiseEffect | null = null;
  private chroma: ChromaticAberrationEffect | null = null;

  private width = 1;
  private height = 1;
  private resolutionScale = 1;
  private frameMs = 0;
  private fps = 0;
  private lastFrameAt = 0;
  private slowFrames = 0;
  private fastFrames = 0;
  private drawCalls = 0;
  private triangles = 0;
  private shadowRadius = 0;

  constructor(
    private readonly parent: HTMLElement,
    sim: SimView,
    view: ViewState,
    params: UrlParams,
    modules: readonly Module[] = MODULES,
  ) {
    this.canvas = document.createElement('canvas');
    parent.appendChild(this.canvas);
    let renderer: THREE.WebGLRenderer;
    try {
      renderer = new THREE.WebGLRenderer({ canvas: this.canvas, antialias: false, powerPreference: 'high-performance', stencil: false, depth: true });
    } catch (err) {
      // no context (GPU busy / lost / too many live contexts): leave no dead canvas behind
      this.canvas.remove();
      throw err;
    }
    this.renderer = renderer;
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    renderer.toneMapping = THREE.NoToneMapping; // tone mapping happens in the effect chain
    renderer.shadowMap.type = THREE.PCFShadowMap;
    renderer.info.autoReset = false;
    try {
      const gl = renderer.getContext();
      const dbg = gl.getExtension('WEBGL_debug_renderer_info');
      this.gpuName = String(dbg ? gl.getParameter(dbg.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER));
    } catch {
      /* ignore */
    }

    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(45, 1, 0.1, 600);
    const sun = new THREE.DirectionalLight(0xffffff, 3);
    sun.castShadow = true;
    sun.shadow.bias = -0.0003;
    sun.shadow.normalBias = 0.04;
    sun.shadow.radius = 2.2;
    scene.add(sun, sun.target);
    const sunMesh = new THREE.Mesh(new THREE.SphereGeometry(1, 16, 12), new THREE.MeshBasicMaterial({ color: 0xfff2d0, transparent: true, depthWrite: false, fog: false, toneMapped: false }));
    sunMesh.frustumCulled = false;
    sunMesh.visible = false;
    scene.add(sunMesh);

    const quality: QualitySettings = { ...QUALITY_PRESETS[params.quality] };
    if (params.shot) quality.dynamicResolution = false;
    this.ctx = {
      renderer,
      scene,
      camera,
      sun,
      sunMesh,
      uniforms: createSharedUniforms(),
      look: createDefaultLook(),
      quality,
      sim,
      view,
      map: sim.map,
      params,
      sync: false,
      stats: { pendingChunks: 0 },
    };

    const inited: Module[] = [];
    this.modules = inited;
    try {
      this.buildChain();
      this.resize();
      for (const m of modules) {
        m.init(this.ctx);
        inited.push(m);
      }
      this.modules = modules;
    } catch (err) {
      // a failed start must not leak the GL context or the canvas: the browser caps live contexts,
      // so leaked ones would make every retry fail too
      for (const m of inited) {
        try {
          m.dispose();
        } catch {
          /* best effort */
        }
      }
      try {
        this.composer?.dispose();
      } catch {
        /* chain may not exist yet */
      }
      renderer.dispose();
      try {
        renderer.forceContextLoss();
      } catch {
        /* already lost */
      }
      this.canvas.remove();
      throw err;
    }
  }

  get gpu(): string {
    return this.gpuName;
  }

  setQuality(preset: QualityPreset): void {
    Object.assign(this.ctx.quality, QUALITY_PRESETS[preset]);
    if (this.ctx.params.shot) this.ctx.quality.dynamicResolution = false;
    this.resolutionScale = 1;
    this.composer.dispose();
    this.buildChain();
    this.resize();
  }

  /** (Re)builds the effect chain for the current quality preset. */
  private buildChain(): void {
    const { renderer, scene, camera, quality: q, sunMesh } = this.ctx;
    renderer.shadowMap.enabled = q.shadows;
    this.ctx.sun.castShadow = q.shadows;
    this.ctx.sun.shadow.mapSize.set(q.shadowMapSize, q.shadowMapSize);
    this.ctx.sun.shadow.map?.dispose();
    this.ctx.sun.shadow.map = null;

    const composer = new EffectComposer(renderer, { frameBufferType: THREE.HalfFloatType, multisampling: 0 });
    this.composer = composer;
    composer.addPass(new RenderPass(scene, camera));

    this.aoPass = null;
    this.aoComposite = null;
    this.bloom = this.dof = this.godRays = this.vignette = this.noise = this.chroma = null;
    this.dofPass = null;

    // --- lit-scene stage: AO composite + depth fog (+ the glow/finish stage when there is no DoF)
    type Fx = AOCompositeEffect | FogEffect | FxScreenEffect | BloomEffect | GodRaysEffect | ToneMappingEffect | HueSaturationEffect | BrightnessContrastEffect | GradeEffect | VignetteEffect | NoiseEffect;
    const stage: Fx[] = [];
    if (q.ssao) {
      this.aoPass = new AOPass(camera, q.preset === 'ultra' ? 16 : 10, q.preset === 'ultra' ? 0.75 : 0.5);
      composer.addPass(this.aoPass);
      this.aoComposite = new AOCompositeEffect(this.aoPass);
      stage.push(this.aoComposite);
    }
    this.fog = new FogEffect(camera);
    stage.push(this.fog);
    if (q.dof) {
      composer.addPass(new EffectPass(camera, ...stage));
      stage.length = 0;
      this.dof = new DepthOfFieldEffect(camera, { focusDistance: 10, focusRange: 6, bokehScale: 2, resolutionScale: q.preset === 'ultra' ? 0.75 : 0.5 });
      // in-focus dead zone: the stock CoC ramps from zero right at the focus distance, which
      // softens flat subjects (farm panes) towards the screen corners
      const coc = this.dof.cocMaterial;
      coc.fragmentShader = coc.fragmentShader.replace('smoothstep(0.0,focusRange,abs(signedDistance))', 'smoothstep(focusRange*0.3,focusRange,abs(signedDistance))');
      coc.needsUpdate = true;
      this.dofPass = new EffectPass(camera, this.dof);
      composer.addPass(this.dofPass);
    }
    if (q.bloom) {
      this.bloom = new BloomEffect({ mipmapBlur: true, intensity: 0.35, luminanceThreshold: 0.85, luminanceSmoothing: 0.2, radius: 0.7, levels: 6 });
      stage.push(this.bloom);
    }
    if (q.godRays && this.ctx.map.environment.backdrop === 'sky') {
      this.godRays = new GodRaysEffect(camera, sunMesh, { samples: q.preset === 'ultra' ? 60 : 36, density: 0.9, decay: 0.92, weight: 0.3, exposure: 0.35, clampMax: 1, resolutionScale: 0.5, blur: true });
      stage.push(this.godRays);
    }
    this.toneMap = new ToneMappingEffect({ mode: ToneMappingMode.ACES_FILMIC });
    this.hueSat = new HueSaturationEffect({ hue: 0, saturation: 0 });
    this.brightCon = new BrightnessContrastEffect({ brightness: 0, contrast: 0 });
    this.grade = new GradeEffect();
    this.fxScreen = new FxScreenEffect(camera);
    stage.push(this.toneMap, this.hueSat, this.brightCon, this.grade, this.fxScreen);
    if (q.lens) {
      this.vignette = new VignetteEffect({ offset: 0.35, darkness: 0.45 });
      this.noise = new NoiseEffect({ blendFunction: BlendFunction.OVERLAY, premultiply: false });
      stage.push(this.vignette, this.noise);
    }
    composer.addPass(new EffectPass(camera, ...stage));
    if (q.lens) {
      this.chroma = new ChromaticAberrationEffect({ offset: new THREE.Vector2(0.0004, 0.0004), radialModulation: true, modulationOffset: 0.3 });
      composer.addPass(new EffectPass(camera, this.chroma));
    }
    if (q.smaa) composer.addPass(new EffectPass(camera, new SMAAEffect({ preset: q.preset === 'ultra' ? SMAAPreset.HIGH : SMAAPreset.MEDIUM })));
  }

  /** Copies `look` into the live effects. Cheap; called every frame. */
  private applyLook(frame: FrameInfo): void {
    const { look, view, renderer } = this.ctx;
    renderer.toneMappingExposure = look.exposure;
    if (this.toneMap) {
      // ToneMappingEffect reads the renderer exposure through this uniform when present.
      const u = this.toneMap.uniforms.get('toneMappingExposure');
      if (u) u.value = look.exposure;
    }
    const env = getEnv(this.ctx);
    const ex = env.extras;
    if (this.aoPass && this.aoComposite) {
      // `look.ssao.radius` is in WORLD units here (contact shadows at ant scale)
      this.aoPass.radius = look.ssao.radius;
      this.aoPass.bias = look.ssao.bias;
      this.aoPass.fade = ex.aoFade;
      this.aoPass.enabled = look.ssao.intensity > 0.001;
      this.aoComposite.intensity = this.aoPass.enabled ? look.ssao.intensity : 0;
    }
    if (this.fog) {
      this.fog.setParams(ex.fogDensity, ex.fogHeight, ex.fogBase);
      this.fog.color.setRGB(ex.fogColor[0], ex.fogColor[1], ex.fogColor[2]);
      this.fog.sunColor.setRGB(ex.fogSunColor[0], ex.fogSunColor[1], ex.fogSunColor[2]);
      this.fog.sunDir.copy(env.sunDir);
      // cloud shadows drift with the wind; broken cloud gives the clearest patches
      const cl = env.cloudiness;
      const broken = Math.min(1, Math.max(0, (cl - 0.12) / 0.3)) * (1 - 0.6 * Math.min(1, Math.max(0, (cl - 0.75) / 0.25)));
      const wind = this.ctx.uniforms.uWind.value;
      this.fog.setCloudShadow(env.room || view.cut.enabled ? 0 : 0.36 * env.day * broken, -fx.clock * (1.1 + wind.x * 2.2), -fx.clock * (0.5 + wind.y * 2.2));
    }
    if (this.grade) this.grade.set(ex.shadowTint, ex.highlightTint, ex.temperature, ex.lift);
    if (this.fxScreen) {
      // B4 screen feedback: kick is a UV shove along its direction, shimmer hugs the ground plane
      const k = fx.kick * fx.kick * 0.022;
      this.fxScreen.set(fx.kickX * k, fx.kickY * k, fx.shimmer, fx.clock, fx.hurt, fx.desat, fx.flash, view.camera.pos.y - fx.shimmerY);
    }
    if (this.bloom) {
      this.bloom.intensity = look.bloom.intensity;
      this.bloom.luminanceMaterial.threshold = look.bloom.threshold;
      this.bloom.luminanceMaterial.smoothing = look.bloom.smoothing;
      this.bloom.mipmapBlurPass.radius = look.bloom.radius;
    }
    if (this.dof && this.dofPass) {
      const on = look.dof.strength > 0.001;
      this.dofPass.enabled = on;
      if (on) {
        const m = this.dof.cocMaterial;
        m.focusDistance = look.dof.autoFocus ? view.camera.focusDist : look.dof.focusDistance;
        m.focusRange = look.dof.focusRange;
        this.dof.bokehScale = look.dof.bokehScale * look.dof.strength;
      }
    }
    if (this.godRays) {
      const g = this.godRays.godRaysMaterial;
      g.exposure = look.godRays.intensity;
      g.decay = look.godRays.decay;
      g.density = look.godRays.density;
      g.weight = look.godRays.weight;
    }
    if (this.hueSat) {
      this.hueSat.saturation = look.grade.saturation;
      this.hueSat.hue = look.grade.hue;
    }
    if (this.brightCon) {
      this.brightCon.brightness = look.grade.brightness;
      this.brightCon.contrast = look.grade.contrast;
    }
    if (this.vignette) {
      this.vignette.offset = look.vignette.offset;
      this.vignette.darkness = look.vignette.darkness;
    }
    if (this.noise) this.noise.blendMode.opacity.value = frame.frozen ? 0 : look.grain; // grain is time-dependent: off in frozen shots
    if (this.chroma) this.chroma.offset.set(look.chromaticAberration, look.chromaticAberration);
  }

  resize(): void {
    const w = Math.max(1, this.parent.clientWidth);
    const h = Math.max(1, this.parent.clientHeight);
    this.width = w;
    this.height = h;
    const pr = Math.min(window.devicePixelRatio || 1, this.ctx.quality.maxPixelRatio) * this.resolutionScale;
    this.renderer.setPixelRatio(pr);
    this.composer.setSize(w, h);
    this.ctx.camera.aspect = w / h;
    this.ctx.camera.updateProjectionMatrix();
  }

  /** Fits the single shadow map to the camera focus region, snapped to shadow texels (§5.3). */
  private fitShadow(): void {
    const { sun, view, uniforms, quality, sunMesh, camera } = this.ctx;
    const env = getEnv(this.ctx);
    const dir = uniforms.uSunDir.value;
    const focus = view.camera.focus;
    // radius grows with zoom; quantised (×√2 steps) so the texel size is stable while zooming
    // (possession: a tight map around the ant gives crisp contact shadows at macro scale)
    const want = THREE.MathUtils.clamp(view.camera.focusDist * 0.85, view.mode === 'possess' ? 6 : 10, 110);
    const quant = Math.pow(Math.SQRT2, Math.ceil(Math.log(want) / Math.log(Math.SQRT2)));
    const r = quant;
    const cam = sun.shadow.camera;
    if (r !== this.shadowRadius) {
      this.shadowRadius = r;
      cam.left = -r;
      cam.right = r;
      cam.top = r;
      cam.bottom = -r;
      cam.near = 1;
      cam.far = r * 4 + 200;
      cam.updateProjectionMatrix();
    }
    // light-space basis
    _up.set(0, 1, 0);
    if (Math.abs(dir.y) > 0.99) _up.set(1, 0, 0);
    _lx.crossVectors(_up, dir).normalize();
    _ly.crossVectors(dir, _lx).normalize();
    _f.set(focus.x, focus.y, focus.z);
    const texel = (2 * r) / quality.shadowMapSize;
    // bias scales with the texel footprint: no acne at canopy zoom, no peter-panning under an ant
    sun.shadow.normalBias = texel * 1.6;
    sun.shadow.bias = -0.00015;
    const sx = Math.round(_f.dot(_lx) / texel) * texel;
    const sy = Math.round(_f.dot(_ly) / texel) * texel;
    const sz = _f.dot(dir);
    _f.set(0, 0, 0).addScaledVector(_lx, sx).addScaledVector(_ly, sy).addScaledVector(dir, sz);
    sun.target.position.copy(_f);
    sun.position.copy(_f).addScaledVector(dir, r * 2 + 100);
    sun.target.updateMatrixWorld();
    sun.updateMatrixWorld();
    // sun disc for god rays: far along the sun direction, relative to the camera
    // (the TRUE sun: `uSunDir` is the key light, which is the moon at night)
    sunMesh.position.copy(camera.position).addScaledVector(env.sunDir, camera.far * 0.9);
    sunMesh.scale.setScalar(camera.far * 0.022);
    sunMesh.visible = !env.room && env.sunDir.y > -0.04;
  }

  /** Renders one frame. */
  render(frame: FrameInfo): void {
    const t0 = performance.now();
    const { camera, view, uniforms, ctx } = { camera: this.ctx.camera, view: this.ctx.view, uniforms: this.ctx.uniforms, ctx: this.ctx };
    if (this.parent.clientWidth !== this.width || this.parent.clientHeight !== this.height) this.resize();

    // camera from the shared view state (written by the input layer)
    const c = view.camera;
    camera.position.set(c.pos.x, c.pos.y, c.pos.z);
    camera.up.set(c.up.x, c.up.y, c.up.z);
    _f.set(c.pos.x + c.forward.x, c.pos.y + c.forward.y, c.pos.z + c.forward.z);
    camera.lookAt(_f);
    if (camera.fov !== c.fov || camera.near !== c.near || camera.far !== c.far) {
      camera.fov = c.fov;
      camera.near = c.near;
      camera.far = c.far;
      camera.updateProjectionMatrix();
      // depth-reading effects (DoF CoC, fog, AO composite, god-ray mask) cache near/far
      this.composer.setMainCamera(camera);
    }
    camera.updateMatrixWorld();

    uniforms.uTime.value = frame.time;
    cutPlaneToVec4(view.cut, uniforms.uCutPlane.value);
    const targetPhero = view.pheroVision ? 1 : 0;
    uniforms.uPheroVision.value = ctx.sync ? targetPhero : uniforms.uPheroVision.value + (targetPhero - uniforms.uPheroVision.value) * Math.min(1, frame.dt * 6);

    for (const m of this.modules) m.update(ctx, frame);
    this.fitShadow();
    this.applyLook(frame);

    this.renderer.info.reset();
    this.composer.render(frame.dt);
    this.drawCalls = this.renderer.info.render.calls;
    this.triangles = this.renderer.info.render.triangles;

    const now = performance.now();
    const cpu = now - t0;
    this.frameMs = this.frameMs === 0 ? cpu : this.frameMs * 0.9 + cpu * 0.1;
    if (this.lastFrameAt > 0) {
      const dt = now - this.lastFrameAt;
      if (dt > 0) this.fps = this.fps === 0 ? 1000 / dt : this.fps * 0.9 + (1000 / dt) * 0.1;
      this.adaptResolution(dt);
    }
    this.lastFrameAt = now;
  }

  /** Blocking render: modules finish deferred work (remeshing) before the frame is drawn. */
  renderSync(frame: FrameInfo): void {
    this.ctx.sync = true;
    try {
      this.render(frame);
      if (!this.warmed) {
        this.warmed = true;
        this.prewarm();
      }
    } finally {
      this.ctx.sync = false;
    }
  }

  /**
   * Shader pre-warm, once, inside the first blocking render (i.e. behind the loading screen):
   * everything that is normally compiled on first use — cutaway shell, first-person rig, weather /
   * night / combat FX meshes that start hidden, the depth-of-field pass — is made visible for one
   * throw-away frame so its programs are compiled and its pipelines created now, not as a hitch on
   * the first cutaway / first night / first possession. The real frame is redrawn afterwards.
   */
  private prewarm(): void {
    const { scene, camera } = this.ctx;
    const cleanups: (() => void)[] = [];
    const hidden: THREE.Object3D[] = [];
    const dofWas = this.dofPass?.enabled ?? false;
    try {
      for (const m of this.modules) {
        const c = m.prewarm?.(this.ctx);
        if (c) cleanups.push(c);
      }
      scene.traverse((o) => {
        if (!o.visible) {
          hidden.push(o);
          o.visible = true;
        }
      });
      if (this.dofPass) this.dofPass.enabled = true;
      this.renderer.compile(scene, camera);
      this.composer.render(0);
    } catch (err) {
      console.warn('[render] shader pre-warm skipped:', err);
    } finally {
      for (const o of hidden) o.visible = false;
      if (this.dofPass) this.dofPass.enabled = dofWas;
      for (const c of cleanups) c();
    }
    // redraw the real first frame (no module updates: frame events must not be consumed twice)
    this.renderer.info.reset();
    this.composer.render(0);
    this.drawCalls = this.renderer.info.render.calls;
    this.triangles = this.renderer.info.render.triangles;
  }

  private adaptResolution(frameDtMs: number): void {
    const q = this.ctx.quality;
    if (!q.dynamicResolution || this.ctx.sync) return;
    if (frameDtMs > 24) this.slowFrames++;
    else if (frameDtMs < 17.5) this.fastFrames++;
    if (this.slowFrames + this.fastFrames < 45) return;
    let s = this.resolutionScale;
    if (this.slowFrames > 30) s = Math.max(q.minResolutionScale, s - 0.1);
    else if (this.fastFrames > 42) s = Math.min(1, s + 0.05);
    this.slowFrames = this.fastFrames = 0;
    if (s !== this.resolutionScale) {
      this.resolutionScale = s;
      this.resize();
    }
  }

  stats(): RenderStats {
    const info = this.renderer.info;
    return {
      drawCalls: this.drawCalls,
      triangles: this.triangles,
      geometries: info.memory.geometries,
      textures: info.memory.textures,
      frameMs: this.frameMs,
      fps: this.fps,
      pendingChunks: this.ctx.stats.pendingChunks,
      resolutionScale: this.resolutionScale,
    };
  }

  dispose(): void {
    for (const m of this.modules) m.dispose();
    this.composer.dispose();
    this.renderer.dispose();
    this.canvas.remove();
  }
}

const _up = new THREE.Vector3();
const _lx = new THREE.Vector3();
const _ly = new THREE.Vector3();
const _f = new THREE.Vector3();
